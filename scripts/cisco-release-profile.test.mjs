import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import {
  containsCiscoProfileData,
  readReleaseProfileSource,
  secureDelete,
  validateReleaseProfile,
} from "./cisco-release-profile.mjs";

const valid = [
  "OCIRCUIT_CISCO_ISSUER=https://login.microsoftonline.com/00000000-0000-4000-8000-000000000000/v2.0",
  "OCIRCUIT_CISCO_CLIENT_ID=11111111-1111-4111-8111-111111111111",
  "OCIRCUIT_CISCO_SCOPES=openid offline_access",
  "OCIRCUIT_CISCO_GATEWAY_BASE=https://organon.cisco.com/vscode-plugin",
  "OCIRCUIT_CISCO_MODEL_POLICY_PATH=/api/model-policy",
  "OCIRCUIT_CISCO_MODEL_API_VERSION=2024-07-01-preview",
].join("\n");

test("accepts and canonicalizes an approved profile", () => {
  const output = validateReleaseProfile(`# comment\n${valid}\n`);
  assert.match(
    output,
    /^# Generated by the protected internal release job\.\n/,
  );
  assert.ok(output.endsWith(`${valid}\n`));
});

test("rejects unapproved or malformed profile values", () => {
  for (const [from, to] of [
    ["organon.cisco.com", "example.com"],
    ["login.microsoftonline.com", "login.example.com"],
    ["/v2.0", "/v1.0"],
    ["CLIENT_ID=11111111-1111-4111-8111-111111111111", "CLIENT_ID=not-a-uuid"],
    ["openid offline_access", "offline_access"],
    ["2024-07-01-preview", "latest"],
    ["/api/model-policy", "/api/model-policy?x=1"],
    ["OCIRCUIT_CISCO_SCOPES", "OCIRCUIT_CISCO_UNKNOWN"],
    ["vscode-plugin", "vscode-plugin\nOCIRCUIT_CISCO_GATEWAY_BASE=x"],
  ]) {
    assert.throws(() => validateReleaseProfile(valid.replace(from, to)), {
      message: /Cisco release profile/,
    });
  }
});

test("reads only private, regular release profile files", () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "oc-profile-test-"));
  try {
    const file = path.join(directory, "profile.env");
    fs.writeFileSync(file, valid, { mode: 0o600 });
    assert.equal(
      readReleaseProfileSource({ OCIRCUIT_RELEASE_CISCO_PROFILE_FILE: file }),
      valid,
    );
    fs.chmodSync(file, 0o644);
    assert.throws(
      () =>
        readReleaseProfileSource({ OCIRCUIT_RELEASE_CISCO_PROFILE_FILE: file }),
      /mode 0600/,
    );
    const link = path.join(directory, "link.env");
    fs.symlinkSync(file, link);
    assert.throws(
      () =>
        readReleaseProfileSource({ OCIRCUIT_RELEASE_CISCO_PROFILE_FILE: link }),
      /regular file/,
    );
    fs.chmodSync(file, 0o600);
    assert.equal(readReleaseProfileSource({}, file), valid);
    assert.throws(
      () =>
        readReleaseProfileSource({
          OCIRCUIT_RELEASE_CISCO_PROFILE: valid,
          OCIRCUIT_RELEASE_CISCO_PROFILE_FILE: file,
        }),
      /only one/,
    );
    assert.throws(
      () => readReleaseProfileSource({}, path.join(directory, "missing.env")),
      /not found/,
    );

    secureDelete(file);
    assert.equal(fs.existsSync(file), false);
    secureDelete(file);
  } finally {
    fs.rmSync(directory, { recursive: true, force: true });
  }
});

test("detects Cisco profile data in public package files", () => {
  assert.equal(containsCiscoProfileData("profiles/cisco-circuit.env"), true);
  assert.equal(containsCiscoProfileData("templates/cisco-circuit.env"), true);
  assert.equal(containsCiscoProfileData("README.md", valid), true);
  assert.equal(
    containsCiscoProfileData(
      "dist/index.js",
      'const CISCO_CIRCUIT_ISSUER = "OCIRCUIT_CISCO_ISSUER";',
    ),
    false,
  );
});
